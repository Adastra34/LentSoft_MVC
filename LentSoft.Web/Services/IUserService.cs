using LentSoft.Web.Models.Entities;
using LentSoft.Web.Models.ViewModels;

namespace LentSoft.Web.Services;

/// <summary>
/// Contrato del servicio de gestión de usuarios y clientes.
/// Centraliza la consulta de usuarios, administración de perfiles, cambio de contraseñas
/// y operaciones CRUD para clientes bajo las políticas de administración del sistema.
/// </summary>
public interface IUserService
{
    /// <summary>
    /// Obtiene la lista de usuarios ordenados por nombre.
    /// Utiliza AsNoTracking para optimizar la consulta de solo lectura.
    /// </summary>
    /// <param name="includeInactive">Indica si se deben incluir usuarios con estado inactivo.</param>
    /// <returns>Lista de entidades <see cref="User"/>.</returns>
    Task<List<User>> GetAllAsync(bool includeInactive = false);

    /// <summary>
    /// Busca un usuario por su identificador único.
    /// </summary>
    /// <param name="id">Identificador del usuario.</param>
    /// <returns>La entidad <see cref="User"/> o <c>null</c> si no se encuentra.</returns>
    Task<User?> GetByIdAsync(int id);

    /// <summary>
    /// Actualiza la información básica del perfil (nombre y teléfono) de un usuario.
    /// </summary>
    /// <param name="id">Identificador del usuario.</param>
    /// <param name="nombre">Nuevo nombre.</param>
    /// <param name="telefono">Nuevo teléfono de contacto.</param>
    /// <returns>La entidad actualizada o <c>null</c> si el usuario no existe.</returns>
    Task<User?> UpdateProfileAsync(int id, string nombre, string? telefono);

    /// <summary>
    /// Modifica la contraseña de un usuario verificando previamente su contraseña actual.
    /// </summary>
    /// <param name="id">Identificador del usuario.</param>
    /// <param name="currentPassword">Contraseña actual en texto plano.</param>
    /// <param name="newPassword">Nueva contraseña a establecer con hash BCrypt.</param>
    /// <returns><c>true</c> si la contraseña actual fue correcta y se actualizó; de lo contrario <c>false</c>.</returns>
    Task<bool> ChangePasswordAsync(int id, string currentPassword, string newPassword);

    /// <summary>
    /// Desactiva lógicamente un usuario en el sistema (<c>Activo = false</c>).
    /// </summary>
    /// <param name="id">Identificador del usuario a desactivar.</param>
    /// <returns><c>true</c> si se desactivó exitosamente; de lo contrario <c>false</c>.</returns>
    Task<bool> DeleteAsync(int id);

    /// <summary>
    /// Reactiva un usuario desactivado previamente en el sistema (<c>Activo = true</c>).
    /// </summary>
    /// <param name="id">Identificador del usuario a reactivar.</param>
    /// <returns><c>true</c> si se reactivó exitosamente; de lo contrario <c>false</c>.</returns>
    Task<bool> ReactivateAsync(int id);

    /// <summary>
    /// Crea un nuevo cliente validando unicidad de correo y requisitos de contraseña.
    /// Si no se especifica contraseña, se genera una aleatoria temporal para posterior definición por enlace.
    /// </summary>
    /// <param name="model">Modelo con los datos del formulario de cliente.</param>
    /// <returns>Tupla con resultado de la operación, mensaje de error en caso de fallo, usuario creado e indicador de contraseña autogenerada.</returns>
    Task<(bool Success, string? ErrorMessage, User? User, bool IsPasswordAutoGenerated)> CreateClientAsync(ClientFormViewModel model);

    /// <summary>
    /// Actualiza la información de un cliente existente comprobando la unicidad del nuevo correo.
    /// </summary>
    /// <param name="model">Modelo con los datos modificados del cliente.</param>
    /// <returns>Tupla indicando si la actualización fue exitosa o el motivo del error.</returns>
    Task<(bool Success, string? ErrorMessage)> UpdateClientAsync(ClientFormViewModel model);

    /// <summary>
    /// Desactiva lógicamente a un usuario asegurando el cumplimiento de las reglas de seguridad:
    /// no auto-desactivación del usuario autenticado y preservación del último administrador activo (RF-M07-03).
    /// </summary>
    /// <param name="id">Identificador del usuario a desactivar.</param>
    /// <param name="currentUserId">Identificador del administrador que ejecuta la acción.</param>
    /// <returns>Tupla indicando éxito o el mensaje de error de negocio correspondiente.</returns>
    Task<(bool Success, string? ErrorMessage)> DeactivateAsync(int id, int currentUserId);
}
